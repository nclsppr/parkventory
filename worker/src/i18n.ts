export function requestLocale(request: Request): Locale {
  const explicit = request.headers.get("X-Parkventory-Locale");
  if (isLocale(explicit)) return explicit;
  return localeFromLanguagePreferences(request.headers.get("Accept-Language"), defaultLocale);
}

export function serverMessage(
  locale: Locale,
  key: ServerMessageKey,
  variables: Record<string, string | number> = {},
) {
  let message: string = serverMessages[locale][key];
  for (const [name, value] of Object.entries(variables)) {
    message = message.replaceAll(`{${name}}`, String(value));
  }
  return message;
}

export function serverMessageCode(key: ServerMessageKey) {
  return key.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase();
}

export type { ServerMessageKey };
